import { useEffect, useState } from "react";
import { useGachaStore } from "../../store/useGachaStore";
import { useProjectStore } from "../../store/useProjectStore";
import { loadThumb } from "./thumbnails";

export function ModelPreviewCard() {
  const winner = useGachaStore((s) => s.winner);
  const manifest = useProjectStore((s) => s.manifest);
  const recordingMs = useProjectStore((s) => s.recordingMs);
  const llmStatus = useProjectStore((s) => s.llmStatus);
  const [src, setSrc] = useState<string>();

  useEffect(() => {
    setSrc(undefined);
    if (winner) loadThumb(winner.thumbnailUrl).then((img) => setSrc(img.src), () => {});
  }, [winner]);

  if (!winner) return <div className="card text-sm text-zinc-400">Spin the wheel to pick today's print. The spin is recorded straight into the project folder.</div>;

  return (
    <div className="card space-y-3">
      <div className="flex gap-3">
        {src ? <img src={src} alt="" className="size-24 shrink-0 rounded-lg object-cover" /> : <div className="size-24 shrink-0 rounded-lg bg-zinc-800" />}
        <div className="min-w-0">
          <p className="text-xs uppercase tracking-wide text-orange-400">{winner.platform}</p>
          <h3 className="font-semibold leading-snug">{winner.title}</h3>
          <p className="text-sm text-zinc-400">by {winner.designer}</p>
          <p className="mt-1 select-all truncate text-xs text-zinc-500">{winner.sourceUrl}</p>
        </div>
      </div>
      {winner.tags.length > 0 && (
        <div className="flex flex-wrap gap-1">
          {winner.tags.slice(0, 10).map((t) => (
            <span key={t} className="rounded bg-zinc-800 px-1.5 py-0.5 text-xs text-zinc-300">
              {t}
            </span>
          ))}
        </div>
      )}
      {manifest && (
        <dl className="space-y-1 text-xs text-zinc-400">
          <div>
            <dt className="inline text-zinc-500">Clip: </dt>
            <dd className="inline select-all break-all">
              {manifest.exportPaths.screenRecordFile} ({((recordingMs ?? 0) / 1000).toFixed(1)}s)
            </dd>
          </div>
          <div>
            <dt className="inline text-zinc-500">Storyboard: </dt>
            <dd className="inline">{{ idle: "starter template", running: "LLM director is writing…", done: "generated by the LLM director", error: "LLM failed, starter template kept" }[llmStatus]}</dd>
          </div>
        </dl>
      )}
    </div>
  );
}
